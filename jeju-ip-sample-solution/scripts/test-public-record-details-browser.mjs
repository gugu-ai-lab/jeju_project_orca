// TourAPI·국가유산청 실제 상세 조회와 카드 이벤트 분리를 5181 브라우저에서 확인한다.
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const origin = process.env.INTEGRATION_PREVIEW_URL || 'http://127.0.0.1:5181'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const blockedExternal = [], errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.hostname === 'api.openai.com' || url.hostname.endsWith('.supabase.co')) {
      blockedExternal.push(url.hostname); return route.abort()
    }
    return route.continue()
  })

  await page.goto(origin + '/places')
  await page.locator('.item-card').first().waitFor()
  await page.locator('form select').selectOption('14')
  await page.getByPlaceholder('검색어').fill('돌문화공원')
  await page.locator('form button[type="submit"]').click()
  const tourCard = page.locator('.item-card').filter({ hasText: '제주돌문화공원' })
  await tourCard.waitFor()
  await tourCard.locator('.item-card-image-trigger').click()
  await page.locator('#public-record-detail-title').getByText('제주돌문화공원', { exact: true }).waitFor()
  await page.locator('.record-detail-description p').filter({ hasText: '제주돌문화공원' }).waitFor()
  await page.locator('.record-detail-photo').waitFor()
  await page.locator('.record-location-map .record-kakao-map[data-map-status="ready"]').waitFor({ timeout: 15000 })
  assert.ok(await page.getByRole('link', { name: /관련 이야기 보기 · 설문대할망/ }).count() === 1)
  const tourMap = await page.locator('.record-kakao-map').evaluate(el => ({ lat: el.dataset.latitude, lng: el.dataset.longitude }))
  assert.equal(tourMap.lat, '33.446621402'); assert.equal(tourMap.lng, '126.663992872')
  const directions = await page.getByRole('link', { name: '카카오맵 길찾기', exact: true }).getAttribute('href')
  assert.match(directions, /map\.kakao\.com\/link\/to\//); assert.match(directions, /33\.446621402/)
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click()
  await page.locator('.modal').waitFor({ state: 'detached' })

  await tourCard.locator('.item-card-title-trigger').click()
  await page.locator('#public-record-detail-title').waitFor()
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click()
  await page.locator('.modal').waitFor({ state: 'detached' })
  await tourCard.locator('.card-body').click({ position: { x: 18, y: 78 } })
  await page.locator('#public-record-detail-title').waitFor()
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click()
  await page.locator('.modal').waitFor({ state: 'detached' })
  await tourCard.getByRole('button', { name: '즐겨찾기' }).click()
  assert.equal(await page.locator('#public-record-detail-title').count(), 0, '즐겨찾기 클릭은 상세 모달을 열지 않아야 함')

  await page.goto(origin + '/heritage')
  await page.locator('.item-card').first().waitFor()
  await page.getByPlaceholder('예: 관덕정, 돌하르방').fill('관덕정')
  await page.locator('form button[type="submit"]').click()
  const heritageCard = page.locator('.item-card').filter({ hasText: '제주 관덕정' })
  await heritageCard.waitFor()
  await heritageCard.locator('.item-card-title-trigger').click()
  await page.locator('#public-record-detail-title').getByText('제주 관덕정', { exact: true }).waitFor()
  await page.locator('.record-detail-description p').filter({ hasText: '제주시내 중심부에 위치' }).waitFor()
  await page.getByText('1963.01.21', { exact: false }).waitFor()
  await page.waitForFunction(() => document.querySelector('.record-detail-photo, .record-detail-photo-placeholder'))
  const heritagePhoto = await page.locator('.record-detail-photo').count() > 0
  if (heritagePhoto) await page.getByRole('dialog').getByRole('link', { name: '공공누리 제1유형(출처표시)' }).waitFor()
  else await page.getByText('확인된 사진이 없습니다', { exact: true }).waitFor()
  await page.locator('.record-location-map .record-kakao-map[data-map-status="ready"]').waitFor({ timeout: 15000 })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok((await page.locator('.modal-dialog').getAttribute('class')).includes('modal-fullscreen-md-down'), '모바일 상세 모달은 화면 전체를 사용해야 함')
  assert.equal(await page.getByRole('link', { name: /관련 이야기 보기/ }).count(), 0, '근거가 일치하지 않는 이야기는 연결하지 않아야 함')
  const heritageMap = await page.locator('.record-kakao-map').evaluate(el => ({ lat: el.dataset.latitude, lng: el.dataset.longitude }))
  assert.equal(heritageMap.lat, '33.5133609436166'); assert.equal(heritageMap.lng, '126.521489474308')
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click()
  await page.locator('.modal').waitFor({ state: 'detached' })
  await heritageCard.locator('.card-body').click({ position: { x: 12, y: 10 } })
  await page.locator('#public-record-detail-title').waitFor()
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click()
  await page.locator('.modal').waitFor({ state: 'detached' })
  await heritageCard.getByRole('button', { name: '즐겨찾기' }).click()
  assert.equal(await page.locator('#public-record-detail-title').count(), 0, '국가유산 즐겨찾기 클릭은 상세 모달을 열지 않아야 함')

  assert.deepEqual(blockedExternal, [])
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ tour: { name: '제주돌문화공원', detail: true, photo: true, address: true, coordinates: tourMap, map: 'ready', directions: true, relatedStory: '설문대할망', imageTitleBodyClicks: true }, heritage: { name: '제주 관덕정', detail: true, photo: heritagePhoto ? '실제 사진과 출처 표시' : '플레이스홀더 유지', designationAndHistory: true, coordinates: heritageMap, map: 'ready', imageTitleBodyClicks: true }, favoriteClickSeparated: true, openAiRequests: 0, supabaseRequests: 0, pageErrors: 0 }))
} finally { await browser.close() }
